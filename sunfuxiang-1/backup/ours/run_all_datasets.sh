#!/usr/bin/env bash
# =============================================================================
# 批量训练 2 个模型结构 × 4 个数据集：
#   模型: ablation-2.yaml / test.yaml
#   数据集: jptomato / raspberry / strawberry / tomato
#
# 通过 MODEL_YAML 环境变量让 main.py 选择模型；每次训练生成一个独立数据
# YAML，训练结束后在终端打印可直接运行的 test 集评估命令。
# =============================================================================
set -uo pipefail

OURS=/home/login/cle/sunfuxiang-1/ours
MAIN=$OURS/main.py
DEFAULT_YAML=$OURS/ultralytics/cfg/default.yaml
COCO8=$OURS/ultralytics/cfg/datasets/coco8.yaml
DATASET_ROOT=/home/login/cle/sunfuxiang-1/dataset
PROJECT_DIR=$OURS/runs/detect
LOG_DIR=$OURS/train_logs
DATA_YAML_DIR=$LOG_DIR/dataset_yamls
SUMMARY=$LOG_DIR/weight_map.txt
PY=${PYTHON:-python}
EPOCHS=${EPOCHS:-300}

MODEL_NAME=(ablation-2 test)
MODEL_YAMLS=(
  "$OURS/ultralytics/cfg/models/ours/ablation-2.yaml"
  "$OURS/ultralytics/cfg/models/ours/test.yaml"
)

DS_NAME=(jptomato raspberry strawberry tomato)
DS_NC=(6 5 3 2)
DS_NAMES=(
  "['i', 'a', 'e', 'is', 'q', 't']"
  "['is', 'a', 'e', 'i', 'yt']"
  "['i', 'a', 'e']"
  "['unripe', 'ripe']"
)

mkdir -p "$LOG_DIR" "$DATA_YAML_DIR"
cd "$OURS" || { echo "无法进入 $OURS，终止"; exit 1; }

BAK_SUFFIX="bak.$$"
cp "$DEFAULT_YAML" "$DEFAULT_YAML.$BAK_SUFFIX" \
  && cp "$COCO8" "$COCO8.$BAK_SUFFIX" \
  || { echo "备份配置文件失败，终止（避免污染原始配置）"; exit 1; }

restore_configs() {
  mv -f "$DEFAULT_YAML.$BAK_SUFFIX" "$DEFAULT_YAML" 2>/dev/null || true
  mv -f "$COCO8.$BAK_SUFFIX" "$COCO8" 2>/dev/null || true
}
trap restore_configs EXIT INT TERM

declare -A STATUS WEIGHTS DATA_YAMLS

echo "=========================================================="
echo "批量训练开始：${#MODEL_NAME[@]} 个模型 × ${#DS_NAME[@]} 个数据集"
echo "解释器: $PY    轮数: $EPOCHS    PID: $$"
echo "=========================================================="

for m in "${!MODEL_NAME[@]}"; do
  model_name="${MODEL_NAME[$m]}"
  model_yaml="${MODEL_YAMLS[$m]}"

  if [ ! -f "$model_yaml" ]; then
    echo "[$model_name] 模型 YAML 不存在：$model_yaml；跳过该模型"
    for name in "${DS_NAME[@]}"; do
      key="${model_name}|${name}"
      STATUS[$key]="SKIP(模型YAML缺失)"
      WEIGHTS[$key]="-"
    done
    continue
  fi

  for i in "${!DS_NAME[@]}"; do
    name="${DS_NAME[$i]}"
    nc="${DS_NC[$i]}"
    names="${DS_NAMES[$i]}"
    root="$DATASET_ROOT/$name"
    key="${model_name}|${name}"
    run_name="${model_name}_${name}"
    log="$LOG_DIR/${run_name}.log"
    data_yaml="$DATA_YAML_DIR/${run_name}.yaml"

    echo
    echo "==================== [$model_name] [$name] (nc=$nc) 开始训练 ===================="

    if [ ! -d "$root/train/images" ] || [ ! -d "$root/val/images" ] || [ ! -d "$root/test/images" ]; then
      echo "[$model_name][$name] 数据集目录不完整 ($root)，跳过"
      STATUS[$key]="SKIP(目录缺失)"
      WEIGHTS[$key]="-"
      continue
    fi

    # 保留每次训练的数据配置，供训练后的 test 命令长期使用。
    cat > "$data_yaml" <<EOF
# Generated by run_all_datasets.sh
train: $root/train
val: $root/val
test: $root/test

nc: $nc
names: $names
EOF
    cp "$data_yaml" "$COCO8"

    sed -i \
      -e "s|^data: .*|data: $COCO8|" \
      -e "s|^project: .*|project: $PROJECT_DIR|" \
      -e "s|^name: .*|name: $run_name|" \
      -e "s|^epochs: .*|epochs: $EPOCHS|" \
      -e "s|^patience: .*|patience: 50|" \
      "$DEFAULT_YAML"

    echo "[$model_name][$name] 模型: $model_yaml"
    echo "[$model_name][$name] 日志: $log"

    if MODEL_YAML="$model_yaml" "$PY" "$MAIN" 2>&1 | tee "$log"; then
      best=$(ls -dt "$PROJECT_DIR"/${run_name}*/weights/best.pt 2>/dev/null | head -1)
      if [ -n "$best" ]; then
        STATUS[$key]="OK"
        WEIGHTS[$key]="$best"
        DATA_YAMLS[$key]="$data_yaml"
        echo "[$model_name][$name] 训练完成 -> $best"
      else
        STATUS[$key]="OK(未找到权重)"
        WEIGHTS[$key]="-"
      fi
    else
      STATUS[$key]="FAIL"
      WEIGHTS[$key]="-"
      echo "[$model_name][$name] 训练失败（见 $log），继续下一项"
    fi
  done
done

echo
echo "=========================================================="
echo "训练完成汇总（模型 / 数据集 / 状态 / 权重）"
echo "=========================================================="
{
  echo "# 生成于 $(date '+%F %T') 解释器=$PY"
  printf "%-12s %-12s %-18s %s\n" "模型" "数据集" "状态" "权重文件"
  for m in "${!MODEL_NAME[@]}"; do
    for i in "${!DS_NAME[@]}"; do
      key="${MODEL_NAME[$m]}|${DS_NAME[$i]}"
      printf "%-12s %-12s %-18s %s\n" "${MODEL_NAME[$m]}" "${DS_NAME[$i]}" "${STATUS[$key]:-UNKNOWN}" "${WEIGHTS[$key]:--}"
    done
  done
} | tee "$SUMMARY"

echo
echo "=========================================================="
echo "测试集评估命令（复制后可直接执行）"
echo "=========================================================="
for m in "${!MODEL_NAME[@]}"; do
  for i in "${!DS_NAME[@]}"; do
    key="${MODEL_NAME[$m]}|${DS_NAME[$i]}"
    best="${WEIGHTS[$key]:-}"
    data_yaml="${DATA_YAMLS[$key]:-}"
    if [ "${STATUS[$key]:-}" = "OK" ] && [ -n "$best" ] && [ -n "$data_yaml" ]; then
      echo "# ${MODEL_NAME[$m]} / ${DS_NAME[$i]}"
      echo "$PY -c \"from ultralytics import YOLO; YOLO(r'$best').val(data=r'$data_yaml', split='test')\""
    fi
  done
done

echo
echo "汇总: $SUMMARY"
echo "数据 YAML: $DATA_YAML_DIR"
echo "default.yaml 与 coco8.yaml 已恢复。"
