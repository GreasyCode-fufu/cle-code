#!/usr/bin/env bash
# =============================================================================
# 使用 main.py 训练 demo.yaml 的 n / s 尺度，分别覆盖 4 个数据集。
#
# n: [0.33, 0.25, 1024]，默认 batch=32（可通过 N_BATCH 覆盖）
# s: [0.33, 0.50, 1024]，默认 batch=16（可通过 S_BATCH 覆盖）
#
# 模型 YAML 文件名必须包含 yolov8n / yolov8s，Ultralytics 才会正确识别
# scales 中的 n / s 配置。脚本结束时会还原 main.py、default.yaml、coco8.yaml。
# =============================================================================
set -uo pipefail

OURS=/home/login/cle/sunfuxiang-1/ours
MAIN=$OURS/main.py
DEFAULT_YAML=$OURS/ultralytics/cfg/default.yaml
COCO8=$OURS/ultralytics/cfg/datasets/coco8.yaml
BASE_MODEL_YAML=$OURS/ultralytics/cfg/models/ours/demo.yaml
DATASET_ROOT=/home/login/cle/sunfuxiang-1/dataset
PROJECT_DIR=$OURS/runs/detect
LOG_DIR=$OURS/train_logs/n_s_experiments
MODEL_YAML_DIR=$LOG_DIR/model_yamls
DATA_YAML_DIR=$LOG_DIR/dataset_yamls
SUMMARY=$LOG_DIR/weight_map.txt
TEST_PROJECT=$PROJECT_DIR/n_s_test_eval
TEST_LOG_DIR=$LOG_DIR/test_logs
TEST_SUMMARY=$LOG_DIR/test_summary.txt
PY=${PYTHON:-python}
EPOCHS=${EPOCHS:-300}
N_BATCH=${N_BATCH:-32}
S_BATCH=${S_BATCH:-16}

SCALES=(n s)
BATCHES=("$N_BATCH" "$S_BATCH")
DS_NAME=(jptomato raspberry strawberry tomato)
DS_NC=(6 5 3 2)
DS_NAMES=(
  "['i', 'a', 'e', 'is', 'q', 't']"
  "['is', 'a', 'e', 'i', 'yt']"
  "['i', 'a', 'e']"
  "['unripe', 'ripe']"
)

mkdir -p "$LOG_DIR" "$MODEL_YAML_DIR" "$DATA_YAML_DIR" "$TEST_PROJECT" "$TEST_LOG_DIR"
cd "$OURS" || { echo "无法进入 $OURS，终止"; exit 1; }

for f in "$MAIN" "$DEFAULT_YAML" "$COCO8" "$BASE_MODEL_YAML"; do
  [ -f "$f" ] || { echo "缺少文件：$f"; exit 1; }
done

BAK_SUFFIX="n_s_bak.$$"
cp "$MAIN" "$MAIN.$BAK_SUFFIX" \
  && cp "$DEFAULT_YAML" "$DEFAULT_YAML.$BAK_SUFFIX" \
  && cp "$COCO8" "$COCO8.$BAK_SUFFIX" \
  || { echo "备份配置文件失败，终止"; exit 1; }

restore_files() {
  mv -f "$MAIN.$BAK_SUFFIX" "$MAIN" 2>/dev/null || true
  mv -f "$DEFAULT_YAML.$BAK_SUFFIX" "$DEFAULT_YAML" 2>/dev/null || true
  mv -f "$COCO8.$BAK_SUFFIX" "$COCO8" 2>/dev/null || true
}
trap restore_files EXIT INT TERM

# main.py 只在本脚本的生命周期内读取 MODEL_YAML；退出时自动恢复原版本。
cat > "$MAIN" <<'PY'
import os
from ultralytics import YOLO

model_yaml = os.environ["MODEL_YAML"]
model = YOLO(model_yaml)
model.train(cfg="/home/login/cle/sunfuxiang-1/ours/ultralytics/cfg/default.yaml")
PY

declare -A STATUS WEIGHTS TEST_STATUS TEST_RESULTS

echo "=========================================================="
echo "开始训练：n / s 两个尺度 × 4 个数据集"
echo "n batch=$N_BATCH，s batch=$S_BATCH，epochs=$EPOCHS，解释器=$PY"
echo "=========================================================="

for sidx in "${!SCALES[@]}"; do
  scale="${SCALES[$sidx]}"
  batch="${BATCHES[$sidx]}"
  # 文件名中的 yolov8n/yolov8s 是 Ultralytics 选择 scales[scale] 的依据。
  model_yaml="$MODEL_YAML_DIR/yolov8${scale}-demo.yaml"
  cp "$BASE_MODEL_YAML" "$model_yaml"

  for didx in "${!DS_NAME[@]}"; do
    dataset="${DS_NAME[$didx]}"
    nc="${DS_NC[$didx]}"
    names="${DS_NAMES[$didx]}"
    root="$DATASET_ROOT/$dataset"
    key="${scale}|${dataset}"
    run_name="demo_${scale}_${dataset}"
    data_yaml="$DATA_YAML_DIR/${run_name}.yaml"
    log="$LOG_DIR/${run_name}.log"

    echo
    echo "==================== [$scale] [$dataset] batch=$batch 开始训练 ===================="

    if [ ! -d "$root/train/images" ] || [ ! -d "$root/val/images" ] || [ ! -d "$root/test/images" ]; then
      echo "[$scale][$dataset] 数据集目录不完整：$root，跳过"
      STATUS[$key]="SKIP(目录缺失)"
      WEIGHTS[$key]="-"
      continue
    fi

    # 每项训练保存独立数据配置，避免 coco8.yaml 恢复后失去对应关系。
    cat > "$data_yaml" <<EOF
# Generated by run_n_s_all_datasets.sh
train: $root/train
val: $root/val
test: $root/test

nc: $nc
names: $names
EOF
    cp "$data_yaml" "$COCO8"

    sed -i \
      -e "s|^data: .*|data: $COCO8|" \
      -e "s|^project: .*|project: $PROJECT_DIR|" \
      -e "s|^name: .*|name: $run_name|" \
      -e "s|^epochs: .*|epochs: $EPOCHS|" \
      -e "s|^batch: .*|batch: $batch|" \
      -e "s|^patience: .*|patience: 50|" \
      "$DEFAULT_YAML"

    echo "[$scale][$dataset] 模型: $model_yaml"
    echo "[$scale][$dataset] 日志: $log"
    if MODEL_YAML="$model_yaml" "$PY" "$MAIN" 2>&1 | tee "$log"; then
      best=$(ls -dt "$PROJECT_DIR"/${run_name}*/weights/best.pt 2>/dev/null | head -1)
      if [ -n "$best" ]; then
        STATUS[$key]="OK"
        WEIGHTS[$key]="$best"
        echo "[$scale][$dataset] 训练完成 -> $best"
      else
        STATUS[$key]="OK(未找到权重)"
        WEIGHTS[$key]="-"
      fi
    else
      STATUS[$key]="FAIL"
      WEIGHTS[$key]="-"
      echo "[$scale][$dataset] 训练失败（见 $log），继续下一项"
    fi
  done
done

echo
echo "=========================================================="
echo "训练完成汇总"
echo "=========================================================="
{
  echo "# 生成于 $(date '+%F %T') 解释器=$PY"
  printf "%-8s %-12s %-10s %-18s %s\n" "尺度" "数据集" "batch" "状态" "权重文件"
  for sidx in "${!SCALES[@]}"; do
    scale="${SCALES[$sidx]}"
    for dataset in "${DS_NAME[@]}"; do
      key="${scale}|${dataset}"
      printf "%-8s %-12s %-10s %-18s %s\n" "$scale" "$dataset" "${BATCHES[$sidx]}" "${STATUS[$key]:-UNKNOWN}" "${WEIGHTS[$key]:--}"
    done
  done
} | tee "$SUMMARY"

echo
echo "=========================================================="
echo "开始测试：对全部成功训练的权重执行 test 集评估"
echo "=========================================================="

for sidx in "${!SCALES[@]}"; do
  scale="${SCALES[$sidx]}"
  for dataset in "${DS_NAME[@]}"; do
    key="${scale}|${dataset}"
    run_name="demo_${scale}_${dataset}"
    weight="${WEIGHTS[$key]:-}"
    data_yaml="$DATA_YAML_DIR/${run_name}.yaml"
    test_log="$TEST_LOG_DIR/${run_name}.log"

    echo
    echo "==================== [$scale] [$dataset] 开始测试 ===================="

    if [ "${STATUS[$key]:-}" != "OK" ] || [ -z "$weight" ] || [ ! -f "$weight" ]; then
      echo "[$scale][$dataset] 没有可用的成功训练权重，跳过测试"
      TEST_STATUS[$key]="SKIP(训练未成功)"
      TEST_RESULTS[$key]="-"
      continue
    fi
    if [ ! -f "$data_yaml" ]; then
      echo "[$scale][$dataset] 数据 YAML 不存在：$data_yaml，跳过测试"
      TEST_STATUS[$key]="SKIP(数据YAML缺失)"
      TEST_RESULTS[$key]="-"
      continue
    fi

    # 使用训练时保存的独立 data YAML，避免 coco8.yaml 恢复后指向错误数据集。
    if "$PY" - "$weight" "$data_yaml" "$TEST_PROJECT" "$run_name" 2>&1 <<'PY' | tee "$test_log"
import sys
from ultralytics import YOLO

weight, data, project, name = sys.argv[1:]
metrics = YOLO(weight).val(data=data, split="test", project=project, name=name, exist_ok=True)
print("TEST_METRICS:", metrics)
PY
    then
      TEST_STATUS[$key]="OK"
      TEST_RESULTS[$key]="$TEST_PROJECT/$run_name"
      echo "[$scale][$dataset] 测试完成 -> ${TEST_RESULTS[$key]}"
    else
      TEST_STATUS[$key]="FAIL"
      TEST_RESULTS[$key]="-"
      echo "[$scale][$dataset] 测试失败（见 $test_log），继续下一项"
    fi
  done
done

echo
echo "=========================================================="
echo "测试完成汇总"
echo "=========================================================="
{
  echo "# 生成于 $(date '+%F %T') 解释器=$PY"
  printf "%-8s %-12s %-18s %s\n" "尺度" "数据集" "测试状态" "测试结果目录"
  for sidx in "${!SCALES[@]}"; do
    scale="${SCALES[$sidx]}"
    for dataset in "${DS_NAME[@]}"; do
      key="${scale}|${dataset}"
      printf "%-8s %-12s %-18s %s\n" "$scale" "$dataset" "${TEST_STATUS[$key]:-UNKNOWN}" "${TEST_RESULTS[$key]:--}"
    done
  done
} | tee "$TEST_SUMMARY"

echo
echo "训练汇总已保存到: $SUMMARY"
echo "测试汇总已保存到: $TEST_SUMMARY"
echo "模型 YAML 副本: $MODEL_YAML_DIR"
echo "数据 YAML 副本: $DATA_YAML_DIR"
echo "测试日志目录: $TEST_LOG_DIR"
echo "测试结果目录: $TEST_PROJECT"
echo "main.py、default.yaml、coco8.yaml 已恢复。"
